/**
 * output-formatters.js - Multi-format export for git-vibe profiles.
 * Supports: JSON, Markdown, SVG badge, Terminal table.
 */

/**
 * Export profile as JSON.
 * @param {object} profile
 * @returns {string} JSON string
 */
export function exportJSON(profile) {
  return JSON.stringify({
    version: '1.0',
    generatedAt: new Date().toISOString(),
    archetype: profile.archetype,
    emoji: profile.emoji,
    vibeScore: profile.vibeScore,
    roast: profile.roast,
    stats: {
      totalCommits: profile.stats.totalCommits,
      author: profile.stats.author,
      nightOwlRatio: profile.stats.nightOwlRatio,
      peakHour: profile.stats.peakHour,
      consistencyScore: profile.stats.consistencyScore,
      messageTypes: profile.stats.messageTypes
    }
  }, null, 2);
}

/**
 * Export profile as Markdown for READMEs.
 * @param {object} profile
 * @returns {string} Markdown string
 */
export function exportMarkdown(profile) {
  const { archetype, emoji, vibeScore, roast, stats } = profile;
  const { totalCommits, nightOwlRatio, peakHour } = stats;

  return `## 🎯 Git Vibe Analysis

| Metric | Value |
|--------|-------|
| **Archetype** | ${archetype} ${emoji} |
| **Total Commits** | ${totalCommits} |
| **Vibe Score** | ${vibeScore} |
| **Night Owl Ratio** | ${Math.round(nightOwlRatio * 100)}% |
| **Peak Hour** | ${peakHour}:00 |
| **Consistency** | ${Math.round(stats.consistencyScore || 0)}% |

> ${roast}

---

*Profile generated by [git-vibe](https://github.com/itznotoroios/git-vibe)*`;
}

/**
 * Export profile as SVG badge.
 * @param {object} profile
 * @param {object} options
 * @returns {string} SVG markup
 */
export function exportSVGBadge(profile, options = {}) {
  const { archetype, emoji, vibeScore, stats } = profile;
  const { author } = stats;
  const { theme = 'brutal' } = options;

  const themes = {
    brutal: { bg: '#F4F4F0', fg: '#050505', accent: '#E61919' },
    dark: { bg: '#0A0A0A', fg: '#EAEAEA', accent: '#E61919' },
    neon: { bg: '#0D0D0D', fg: '#00FF41', accent: '#FF00FF' }
  };

  const t = themes[theme] || themes.brutal;
  const width = 240;
  const height = 40;

  return `
<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <defs>
    <style>
      @import url('https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;700&amp;display=swap');
      .bg { fill: ${t.bg}; }
      .fg { fill: ${t.fg}; }
      .accent { fill: ${t.accent}; }
    </style>
  </defs>
  <rect class="bg" width="${width}" height="${height}" />
  <rect x="0" y="0" width="4" height="${height}" fill="${t.accent}" />
  <text x="16" y="26" font-family="'JetBrains Mono', monospace" font-size="12" font-weight="bold" fill="${t.fg}">${emoji} ${author}</text>
  <text x="${width - 80}" y="26" font-family="'JetBrains Mono', monospace" font-size="11" fill="${t.fg}">${vibeScore.split('/')[0]}</text>
</svg>`;
}

/**
 * Export profile as terminal table.
 * @param {object} profile
 * @returns {string} Formatted table string
 */
export function exportTerminalTable(profile) {
  const { archetype, emoji, vibeScore, roast, stats } = profile;
  const { totalCommits, nightOwlRatio, peakHour, consistencyScore } = stats;

  const pad = (str, len) => str.padEnd(len);
  const separator = '├' + '─'.repeat(40) + '┤';

  return `
${'═'.repeat(44)}
${pad('METRIC', 24)} ${pad('VALUE', 20)}
${separator}
${pad(emoji + ' Archetype', 24)} ${pad(archetype, 20)}
${pad('Total Commits', 24)} ${pad(String(totalCommits), 20)}
${pad('Night Owl %', 24)} ${pad(Math.round(nightOwlRatio * 100) + '%', 20)}
${pad('Peak Hour', 24)} ${pad(peakHour + ':00', 20)}
${pad('Consistency', 24)} ${pad(Math.round(consistencyScore || 0) + '%', 20)}
${pad('Vibe Score', 24)} ${pad(vibeScore, 20)}
${'═'.repeat(44)}
`.trim();
}

/**
 * Auto-select best format based on context.
 * @param {object} profile
 * @param {string} format - 'json', 'md', 'svg', 'table', 'auto'
 * @returns {{ content: string, filename: string, mime: string }}
 */
export function exportProfile(profile, format = 'auto') {
  const formatMap = {
    json: { fn: exportJSON, ext: 'json', mime: 'application/json' },
    md: { fn: exportMarkdown, ext: 'md', mime: 'text/markdown' },
    svg: { fn: exportSVGBadge, ext: 'svg', mime: 'image/svg+xml' },
    table: { fn: exportTerminalTable, ext: 'txt', mime: 'text/plain' }
  };

  // Auto-detect based on environment
  if (format === 'auto') {
    if (typeof process !== 'undefined' && process.stdout.isTTY) {
      return { ...formatMap.table, content: formatMap.table.fn(profile) };
    } else {
      return { ...formatMap.markdown, content: formatMap.markdown.fn(profile) };
    }
  }

  const exporter = formatMap[format];
  if (!exporter) {
    throw new Error(`Unknown format: ${format}. Use: json, md, svg, table`);
  }

  const content = exporter.fn(profile);
  return { ...exporter, content };
}